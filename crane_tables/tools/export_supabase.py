"""
Export the extracted capacity database to Supabase-ready artifacts.

Reads the SQLite built by `build_fleet.py` and writes:

  supabase/schema.sql            DDL (tables, view, RLS) for Supabase/Postgres
  supabase/data/cranes.csv       one row per crane
  supabase/data/charts.csv       one row per load chart (page)
  supabase/data/capacities.csv   one row per capacity cell
  supabase/data/flat.csv         everything denormalised (staging route)
  supabase/seed.sql              schema + INSERTs, run in one go (SQL route)
  supabase/load_from_csv.sql     staging -> normalised transform (CSV route)

Two load routes, both idempotent:

  SQL  : paste/run supabase/seed.sql in the Supabase SQL editor (or psql).
  CSV  : load supabase/data/flat.csv into the `staging_capacity` table
         (Table editor or `supabase db` / psql \\copy), then run
         supabase/load_from_csv.sql.

Usage:
    python3 -m tools.export_supabase db/fleet.db supabase
"""
from __future__ import annotations

import csv
import os
import sqlite3
import sys

SCHEMA = """-- Crane load-chart database (generated by tools/export_supabase.py)
create table if not exists crane (
  id            bigint generated always as identity primary key,
  manufacturer  text not null,
  model         text not null,
  max_capacity_t numeric,
  source_pdf    text,
  unique (manufacturer, model)
);

create table if not exists chart (
  id            bigint generated always as identity primary key,
  crane_id      bigint not null references crane(id) on delete cascade,
  page          int not null,
  system        text not null,
  counterweight_t numeric,
  boom_min      numeric,
  boom_max      numeric,
  jib_m         numeric,
  ballast_options text,
  unique (crane_id, page)
);

create table if not exists capacity (
  id            bigint generated always as identity primary key,
  chart_id      bigint not null references chart(id) on delete cascade,
  radius_m      numeric not null,
  boom_m        numeric,
  angle_deg     numeric,
  footnote      text default '',
  capacity_t    numeric not null
);
create index if not exists idx_capacity_chart on capacity(chart_id);
create index if not exists idx_capacity_lookup on capacity(chart_id, radius_m, boom_m, angle_deg);

-- Flat view for the web front-end (one call returns everything to filter on)
create or replace view v_capacity as
select cr.manufacturer, cr.model as crane, cr.max_capacity_t,
       ch.page, ch.system, ch.counterweight_t, ch.jib_m,
       c.boom_m, c.angle_deg, c.footnote, c.radius_m, c.capacity_t
from capacity c
join chart ch on ch.id = c.chart_id
join crane cr on cr.id = ch.crane_id;

-- Staging table for the CSV route (all text, filled by the CSV loader)
create table if not exists staging_capacity (
  manufacturer text, model text, max_capacity_t text, source_pdf text,
  page text, system text, counterweight_t text, boom_min text, boom_max text,
  jib_m text, ballast_options text, boom_m text, angle_deg text,
  footnote text, radius_m text, capacity_t text
);

-- Row level security: read-only for signed-in users, writes only via service role
alter table crane    enable row level security;
alter table chart    enable row level security;
alter table capacity enable row level security;
-- create the read policies only when running inside Supabase (role exists)
do $$ begin
  if exists (select 1 from pg_roles where rolname = 'authenticated') then
    if not exists (select 1 from pg_policies where tablename='capacity' and policyname='read_capacity') then
      create policy read_capacity on capacity for select to authenticated using (true);
    end if;
    if not exists (select 1 from pg_policies where tablename='chart' and policyname='read_chart') then
      create policy read_chart on chart for select to authenticated using (true);
    end if;
    if not exists (select 1 from pg_policies where tablename='crane' and policyname='read_crane') then
      create policy read_crane on crane for select to authenticated using (true);
    end if;
  end if;
end $$;
"""

FLAT_COLS = ["manufacturer", "model", "max_capacity_t", "source_pdf",
             "page", "system", "counterweight_t", "boom_min", "boom_max",
             "jib_m", "ballast_options", "boom_m", "angle_deg", "footnote",
             "radius_m", "capacity_t"]


def _sql_text(v) -> str:
    if v is None or v == "":
        return "null"
    return "'" + str(v).replace("'", "''") + "'"


def _sql_num(v) -> str:
    return "null" if v is None else repr(float(v))


def _read(db: str):
    con = sqlite3.connect(db)
    con.row_factory = sqlite3.Row
    rows = con.execute("""
        select cr.manufacturer, cr.model, cr.max_capacity_t, cr.source_pdf,
               ch.page, ch.system, ch.counterweight_t, ch.boom_min, ch.boom_max,
               ch.jib_m, ch.ballast_options,
               c.radius_m, c.boom_m, c.angle_deg, c.footnote, c.capacity_t
        from capacity c
        join chart ch on ch.id = c.chart_id
        join crane cr on cr.id = ch.crane_id
        order by cr.model, ch.page, c.boom_m, c.angle_deg, c.radius_m
    """).fetchall()
    con.close()
    return rows


def _write_csv(path: str, header: list[str], rows):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(header)
        w.writerows(rows)
    print(f"  wrote {len(rows):>6} rows -> {path}")


def export(db: str, out_dir: str):
    rows = _read(db)
    os.makedirs(out_dir, exist_ok=True)
    data_dir = os.path.join(out_dir, "data")

    # ---- CSVs (normalised) ------------------------------------------------
    cranes, charts = {}, {}
    for r in rows:
        cranes[(r["manufacturer"], r["model"])] = (r["manufacturer"], r["model"],
                                                   r["max_capacity_t"], r["source_pdf"])
        charts[(r["manufacturer"], r["model"], r["page"])] = (
            r["manufacturer"], r["model"], r["page"], r["system"],
            r["counterweight_t"], r["boom_min"], r["boom_max"], r["jib_m"],
            r["ballast_options"])
    _write_csv(os.path.join(data_dir, "cranes.csv"),
               ["manufacturer", "model", "max_capacity_t", "source_pdf"],
               list(cranes.values()))
    _write_csv(os.path.join(data_dir, "charts.csv"),
               ["manufacturer", "model", "page", "system", "counterweight_t",
                "boom_min", "boom_max", "jib_m", "ballast_options"],
               list(charts.values()))
    _write_csv(os.path.join(data_dir, "capacities.csv"),
               ["manufacturer", "model", "page", "boom_m", "angle_deg",
                "footnote", "radius_m", "capacity_t"],
               [(r["manufacturer"], r["model"], r["page"], r["boom_m"],
                 r["angle_deg"], r["footnote"], r["radius_m"], r["capacity_t"])
                for r in rows])
    _write_csv(os.path.join(data_dir, "flat.csv"), FLAT_COLS,
               [[r[c] if r[c] is not None else "" for c in FLAT_COLS]
                for r in rows])

    # ---- schema.sql -------------------------------------------------------
    with open(os.path.join(out_dir, "schema.sql"), "w") as fh:
        fh.write(SCHEMA)
    print(f"  wrote schema.sql")

    # ---- seed.sql (schema + inserts, one shot) ----------------------------
    L = [SCHEMA, "\nbegin;\n",
         "-- full reset (cascades to chart/capacity)\n",
         "delete from capacity; delete from chart; delete from crane;\n\n",
         "-- cranes\n",
         "insert into crane(manufacturer,model,max_capacity_t,source_pdf) values\n"]
    L.append(",\n".join(
        f"({_sql_text(m)},{_sql_text(md)},{_sql_num(mc)},{_sql_text(sp)})"
        for (m, md), (_, _, mc, sp) in
        {k: v for k, v in cranes.items()}.items()) + ";\n\n")

    L.append("-- charts\n")
    chartvals = [(m, md, pg, sy, cw, bmin, bmax, jb, bo)
                 for (m, md, pg), (_, _, _, sy, cw, bmin, bmax, jb, bo)
                 in charts.items()]
    L.append("insert into chart(crane_id,page,system,counterweight_t,boom_min,"
             "boom_max,jib_m,ballast_options)\n"
             "select cr.id, v.page, v.system, v.counterweight_t, v.boom_min,"
             " v.boom_max, v.jib_m, v.ballast_options\nfrom (values\n")
    L.append(",\n".join(
        f"({_sql_text(m)},{_sql_text(md)},{int(pg)},{_sql_text(sy)},"
        f"{_sql_num(cw)},{_sql_num(bmin)},{_sql_num(bmax)},{_sql_num(jb)},"
        f"{_sql_text(bo)})"
        for (m, md, pg, sy, cw, bmin, bmax, jb, bo) in chartvals))
    L.append("\n) as v(manufacturer,model,page,system,counterweight_t,boom_min,"
             "boom_max,jib_m,ballast_options)\n"
             "join crane cr on cr.manufacturer=v.manufacturer and cr.model=v.model;\n\n")

    L.append("-- capacity (batched)\n")
    batch, B = [], 2000
    def flush(batch):
        L.append("insert into capacity(chart_id,radius_m,boom_m,angle_deg,"
                 "footnote,capacity_t)\nselect ch.id, v.radius_m, v.boom_m, "
                 "v.angle_deg, v.footnote, v.capacity_t\nfrom (values\n")
        L.append(",\n".join(
            f"({_sql_text(m)},{_sql_text(md)},{int(pg)},{_sql_num(ra)},"
            f"{_sql_num(bm)},{_sql_num(an)},{_sql_text(fn)},{_sql_num(cp)})"
            for (m, md, pg, ra, bm, an, fn, cp) in batch))
        L.append("\n) as v(manufacturer,model,page,radius_m,boom_m,angle_deg,"
                 "footnote,capacity_t)\n"
                 "join crane cr on cr.manufacturer=v.manufacturer and cr.model=v.model\n"
                 "join chart ch on ch.crane_id=cr.id and ch.page=v.page;\n")
    for r in rows:
        batch.append((r["manufacturer"], r["model"], r["page"], r["radius_m"],
                      r["boom_m"], r["angle_deg"], r["footnote"], r["capacity_t"]))
        if len(batch) >= B:
            flush(batch); batch = []
    if batch:
        flush(batch)
    L.append("\ncommit;\n")
    with open(os.path.join(out_dir, "seed.sql"), "w") as fh:
        fh.write("".join(L))
    print(f"  wrote seed.sql")

    # ---- load_from_csv.sql (staging transform) ----------------------------
    with open(os.path.join(out_dir, "load_from_csv.sql"), "w") as fh:
        fh.write("""-- Route CSV: after loading supabase/data/flat.csv into staging_capacity
-- (Table editor / psql \\copy / supabase db), run this in the SQL editor.
begin;

insert into crane(manufacturer,model,max_capacity_t,source_pdf)
select distinct manufacturer, model, max_capacity_t::numeric, source_pdf
from staging_capacity
on conflict (manufacturer,model) do update
  set max_capacity_t = excluded.max_capacity_t,
      source_pdf     = excluded.source_pdf;

insert into chart(crane_id,page,system,counterweight_t,boom_min,boom_max,jib_m,ballast_options)
select cr.id, s.page::int, s.system,
       nullif(s.counterweight_t,'')::numeric, nullif(s.boom_min,'')::numeric,
       nullif(s.boom_max,'')::numeric, nullif(s.jib_m,'')::numeric, s.ballast_options
from (select distinct manufacturer,model,page,system,counterweight_t,boom_min,
             boom_max,jib_m,ballast_options from staging_capacity) s
join crane cr on cr.manufacturer=s.manufacturer and cr.model=s.model
on conflict (crane_id,page) do update
  set system=excluded.system, counterweight_t=excluded.counterweight_t,
      boom_min=excluded.boom_min, boom_max=excluded.boom_max,
      jib_m=excluded.jib_m, ballast_options=excluded.ballast_options;

-- replace the capacities of the cranes present in the staging table
delete from capacity where chart_id in (
  select ch.id from chart ch join crane cr on cr.id=ch.crane_id
  where (cr.manufacturer,cr.model) in
        (select distinct manufacturer,model from staging_capacity));

insert into capacity(chart_id,radius_m,boom_m,angle_deg,footnote,capacity_t)
select ch.id, s.radius_m::numeric, nullif(s.boom_m,'')::numeric,
       nullif(s.angle_deg,'')::numeric, coalesce(s.footnote,''), s.capacity_t::numeric
from staging_capacity s
join crane cr on cr.manufacturer=s.manufacturer and cr.model=s.model
join chart ch on ch.crane_id=cr.id and ch.page=s.page::int;

truncate staging_capacity;
commit;
""")
    print(f"  wrote load_from_csv.sql")


if __name__ == "__main__":
    db = sys.argv[1] if len(sys.argv) > 1 else "db/fleet.db"
    out = sys.argv[2] if len(sys.argv) > 2 else "supabase"
    export(db, out)
